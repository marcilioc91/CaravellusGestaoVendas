-- Evento obrigatorio e ligado a tabela EVENTO

ALTER TABLE CATEGORIA ALTER COLUMN EVENTO_CODIGO SET NOT NULL;
ALTER TABLE PRODUTO ALTER COLUMN EVENTO_CODIGO SET NOT NULL;
ALTER TABLE CLIENTE ALTER COLUMN EVENTO_CODIGO SET NOT NULL;
ALTER TABLE VENDA ALTER COLUMN EVENTO_CODIGO SET NOT NULL;

ALTER TABLE CATEGORIA ADD CONSTRAINT FK_CATEGORIA_EVENTO FOREIGN KEY (EVENTO_CODIGO) REFERENCES EVENTO (CODIGO);
ALTER TABLE PRODUTO ADD CONSTRAINT FK_PRODUTO_EVENTO FOREIGN KEY (EVENTO_CODIGO) REFERENCES EVENTO (CODIGO);
ALTER TABLE CLIENTE ADD CONSTRAINT FK_CLIENTE_EVENTO FOREIGN KEY (EVENTO_CODIGO) REFERENCES EVENTO (CODIGO);
ALTER TABLE VENDA ADD CONSTRAINT FK_VENDA_EVENTO FOREIGN KEY (EVENTO_CODIGO) REFERENCES EVENTO (CODIGO);
ALTER TABLE AUDITORIA_LOG ADD CONSTRAINT FK_AUDITORIA_LOG_EVENTO FOREIGN KEY (EVENTO_CODIGO) REFERENCES EVENTO (CODIGO);

-- PESSOA continua unica para o sistema todo (CPF unico; usuarios sao pessoas).
-- A mesma pessoa pode ser cliente em varios eventos, mas so uma vez em cada um.
ALTER TABLE CLIENTE DROP CONSTRAINT UK_CLIENTE_PESSOA;
ALTER TABLE CLIENTE ADD CONSTRAINT UK_CLIENTE_EVENTO_PESSOA UNIQUE (EVENTO_CODIGO, PESSOA_ID);
